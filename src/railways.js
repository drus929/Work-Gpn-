// Обобщённые районы обслуживания филиалов РЖД для обзорной карты.
// Это авторская схема, а не официальные границы дорог или субъектов РФ.
// Соседние дороги могут обслуживать один регион: полигоны допускают перекрытие.
// На карте геометрия должна дополнительно обрезаться по контуру суши России.

function polygon(points) {
  // d3-geo использует обход внешнего кольца по часовой стрелке.
  const area = points.reduce((sum, [x, y], index) => {
    const next = points[(index + 1) % points.length];
    return sum + x * next[1] - next[0] * y;
  }, 0);
  const ring = area > 0 ? [...points].reverse() : [...points];
  return { type: 'Polygon', coordinates: [[...ring, [...ring[0]]]] };
}

